// What the open page does once a new build has taken it over (composables/appUpdate.ts):
// reload while nobody has used the page or the tab is in the background, wait for the
// page's own moment on a bare (kiosk) route, otherwise an in-app notice with a Reload
// button. Never a blocking dialog. The notice is a toast; it is raised only from a
// service-worker event, after the Pinia instance below exists.
const onNewBuild = watchAppUpdate(router, browserUpdateEffects(window, (notice) => {
	useNotificationStore(pinia).pushLocalNotification({ ...notice, level: "info", sticky: true });
}));

// Register the service worker generated by vite-plugin-pwa.  `immediate: true`
// activates the SW on first load (so a refresh isn't required to pick it up),
// and `autoUpdate` mode means new builds install in the background and claim the
// open tabs. Stale bundles must not linger after deploys, nor may a reload land
// under someone's hands: serviceWorkerHooks hands the moment the new build has
// taken over to onNewBuild (without `onNeedReload` the plugin reloads on the spot).
const updateSW = registerSW({
	immediate: true,
	...serviceWorkerHooks(onNewBuild, () => void updateSW(true)),
	onRegisteredSW(_swUrl, registration) {
		if (!registration || typeof window === "undefined") return;
		window.setInterval(() => {
			void registration.update();
		}, 60_000);
	},
	onRegisterError(error) {
		console.error("Service worker registration failed:", error);
	},
});

const CHUNK_RELOAD_KEY = "starlingai:chunk-reload-target";

function isDynamicImportFailure(error: unknown): boolean {
	const message = error instanceof Error ? error.message : String(error ?? "");
	return /Failed to fetch dynamically imported module|Importing a module script failed|error loading dynamically imported module/i.test(message);
}

router.onError((error, to) => {
	if (!isDynamicImportFailure(error)) {
		console.error(error);
		return;
	}

	const target = to.fullPath || window.location.pathname + window.location.search + window.location.hash;
	const previousTarget = window.sessionStorage.getItem(CHUNK_RELOAD_KEY);
	if (previousTarget === target) {
		window.sessionStorage.removeItem(CHUNK_RELOAD_KEY);
		console.error(error);
		return;
	}

	window.sessionStorage.setItem(CHUNK_RELOAD_KEY, target);
	window.location.assign(target);
});

router.afterEach(() => {
	window.sessionStorage.removeItem(CHUNK_RELOAD_KEY);
});

const app = createApp(App);
// App-level error boundary: a thrown render/lifecycle error in one component is
// logged and contained here instead of tearing down the whole dashboard. (Vue
// still unmounts the failing subtree, but sibling views keep working.)
app.config.errorHandler = (err, _instance, info) => {
  console.error(`[vue] unhandled component error (${info}):`, err);
};
const pinia = createPinia();
app.use(pinia);
app.use(router);
// Apply the persisted theme before mount so a non-default theme doesn't flash
// the default palette on first paint.
useThemeStore(pinia).init();

// Same reasoning for product identity (docs/fork-boilerplate-plan.md WS1): a fork's
// name/tagline/logo must not flash upstream's branding on first paint, and the login
// screen renders BEFORE any token exists (which is why /api/product is public). The
// load is bounded — a slow or unreachable gateway delays first paint by at most this
// long instead of hanging the shell, and the store keeps its upstream defaults on any
// failure. It is reactive, so a late response still updates the UI after mount.
const PRODUCT_LOAD_TIMEOUT_MS = 1_500;
void (async () => {
	await Promise.race([
		useProductStore(pinia).load(),
		new Promise<void>((resolve) => { window.setTimeout(resolve, PRODUCT_LOAD_TIMEOUT_MS); }),
	]);
	app.mount("#app");
})();
